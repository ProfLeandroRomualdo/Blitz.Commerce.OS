-- Blitz Commerce OS PostgreSQL baseline. Idempotent bootstrap migration.
-- Execute with least-privilege schema-owner user, NOT a global postgres superuser.
CREATE TABLE IF NOT EXISTS tenants (
  id TEXT PRIMARY KEY,
  slug TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  api_key_hash TEXT NOT NULL,
  checkout_url TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_tenants_api_key_hash ON tenants(api_key_hash);
CREATE TABLE IF NOT EXISTS platform_bindings (
  tenant_id TEXT NOT NULL REFERENCES tenants(id),
  profile_url TEXT NOT NULL,
  PRIMARY KEY (tenant_id, profile_url)
);
CREATE TABLE IF NOT EXISTS products (
  tenant_id TEXT NOT NULL REFERENCES tenants(id),
  sku TEXT NOT NULL,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  price_cents BIGINT NOT NULL CHECK (price_cents >= 0),
  stock INTEGER NOT NULL CHECK (stock >= 0),
  PRIMARY KEY (tenant_id, sku)
);
CREATE TABLE IF NOT EXISTS carts (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants(id),
  status TEXT NOT NULL,
  body TEXT NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_carts_tenant ON carts(tenant_id);
CREATE TABLE IF NOT EXISTS checkouts (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants(id),
  status TEXT NOT NULL,
  body TEXT NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_checkouts_tenant ON checkouts(tenant_id);
CREATE TABLE IF NOT EXISTS events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants(id),
  event_type TEXT NOT NULL,
  resource_id TEXT,
  created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_events_tenant_time ON events(tenant_id, created_at);
CREATE TABLE IF NOT EXISTS idempotency (
  tenant_id TEXT NOT NULL,
  key TEXT NOT NULL,
  fingerprint TEXT NOT NULL,
  response_json TEXT NOT NULL,
  PRIMARY KEY (tenant_id, key)
);
CREATE TABLE IF NOT EXISTS signature_nonces (
  profile TEXT NOT NULL,
  identity TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  PRIMARY KEY(profile, identity)
);
CREATE INDEX IF NOT EXISTS idx_signature_nonces_created ON signature_nonces(created_at);
